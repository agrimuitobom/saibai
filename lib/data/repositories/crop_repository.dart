  List<CropModel> getAllCrops() {
    return _allCrops;
  }

  List<CropModel> searchCrops(String query) {
    if (query.isEmpty) return _allCrops;
    final q = query.toLowerCase();
    return _allCrops
        .where((c) => c.name.toLowerCase().contains(q))
        .toList();
  }

  CropModel? getCropById(String id) {
    try {
      return _allCrops.firstWhere((c) => c.id == id);
    } catch (_) {
      return null;
    }
  }
